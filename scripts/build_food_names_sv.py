"""Writes js/food-names-sv.js (food id -> approved Swedish display name, from scripts/food_sv.py NAMES) for the Swedish
view of foods.html, and stamps its content hash into foods.html (js/* is served with a one-year immutable cache).

foods.html loads the file only when the Swedish view is chosen, so the AR / EN / NL views download nothing extra.
Rerun after NAMES changes in food_sv.py:  python scripts/build_food_names_sv.py
"""
import hashlib
import json
import re
from pathlib import Path

from food_sv import NAMES

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / 'js' / 'food-names-sv.js'
PAGE = ROOT / 'foods.html'


def main():
    names = {str(fid): NAMES[fid][0] for fid in sorted(NAMES)}
    OUT.write_text('// Generated by scripts/build_food_names_sv.py - do not edit by hand.\n'
                   '// Food id -> approved Swedish display name (scripts/food_sv.py NAMES), loaded by foods.html in Swedish.\n'
                   'window.FOOD_NAMES_SV = ' + json.dumps(names, ensure_ascii=False, separators=(',', ':')) + ';\n',
                   encoding='utf-8', newline='\n')
    ver = hashlib.sha1(OUT.read_bytes()).hexdigest()[:8]
    text = PAGE.read_text(encoding='utf-8')
    new, n = re.subn(r"'/js/food-names-sv\.js(?:\?v=[^']*)?'", f"'/js/food-names-sv.js?v={ver}'", text)
    if n != 1:
        raise SystemExit(f'foods.html: expected one food-names-sv.js reference, found {n}')
    if new != text:
        PAGE.write_text(new, encoding='utf-8', newline='\n')
    print(f'{OUT.name}: {len(names)} names, {OUT.stat().st_size} bytes, v={ver}')


if __name__ == '__main__':
    main()
