"""Batch 30: turns the approved Arabic copy (ar_corrected_part1.md + ar_corrected_part2.md) into the merge format
(ar.md, same keys as scripts/batch28) and foods.json (names, numbers, GI/GL) for data.js and the translations.
Checks every per-100 g number and GL against js/data.js and prints the differences.
Usage: python -X utf8 -I build_ar.py   (run from scripts/batch30)"""
import json
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent

SLUG = {876: 'liege-syrup', 877: 'honingkoek', 883: 'soto-ayam', 884: 'wilhelmina-peppermints', 886: 'honingdrop',
        887: 'buckwheat-kasha', 888: 'rassolnik', 889: 'polish-mushroom-soup', 890: 'bigos', 891: 'herring-beetroot-salad',
        892: 'lohikeitto', 893: 'ruisleipa', 894: 'karjalanpiirakka', 895: 'babgulyas', 896: 'shopska-salad',
        897: 'banitsa', 898: 'cevapi', 899: 'ajvar', 900: 'pindjur', 901: 'roti-kip', 902: 'dhalpuri',
        903: 'kousenband', 904: 'pom', 905: 'bara', 909: 'beef-rendang'}
PUBLISHED = {893: 'Atkinson FS, Brand-Miller JC, Foster-Powell K, Buyken AE, Goletzke J. International tables of glycemic '
                  'index and glycemic load values 2021: a systematic review. Am J Clin Nutr. 2021;114(5):1625–32.'}
UNAVAILABLE = {886}
HEAD = {'🟢': 'توصيات الاستهلاك', '🍴': 'أفضل طرق التحضير', '⚠️': 'ملاحظة غذائية هامة ⚠️'}


def num(block, label):
    m = re.search(label + r': ([\d.]+)', block)
    return float(m.group(1)) if m else None


def parse(block):
    lines = block.strip().split('\n')
    f = {'id': int(re.search(r'\(#(\d+)\)', lines[0]).group(1)), 'ar': lines[0].split('): ', 1)[1].strip()}
    for key, label in (('en', 'الاسم الإنجليزي'), ('nl', 'الاسم الهولندي'), ('sv', 'الاسم السويدي'),
                       ('title', 'عنوان السيرش'), ('desc', r'وصف السيرش \(Meta\)'), ('brand', 'ملاحظة العلامة التجارية')):
        m = re.search(r'(?m)^' + label + r': (.*)$', block)
        f[key] = m.group(1).strip() if m else None
    cat, portion = re.search(r'(?m)^الفئة: (.*?) \| الحصة المعتادة: (.*)$', block).groups()
    f['category'], f['portion_txt'] = cat.strip(), portion.strip()
    f['portion'] = float(re.findall(r'([\d.]+) غ\)', portion)[-1])
    for key, label in (('kcal', 'السعرات'), ('carbs', 'الكربوهيدرات'), ('fiber', 'الألياف'), ('protein', 'البروتين'),
                       ('fat', 'الدهون')):
        f[key] = num(block, label)
    f['gi_line'] = re.search(r'(?m)^المؤشر الجلايسيمي \(GI\): (.*)$', block).group(1).strip()
    f['gl_line'] = re.search(r'(?m)^الحمل الجلايسيمي \(GL\): (.*)$', block).group(1).strip()
    m = re.match(r'(\d+) \(', f['gi_line'])
    f['gi'] = int(m.group(1)) if m else None
    f['pulse'] = re.search(r'سرد الوجبة\):\n"?(.*?)"?\n4\.', block, re.S).group(1).strip().strip('"')
    tips = re.search(r'الإرشاد الغذائي الذكي:\n(.*?)\n5\. ', block, re.S).group(1)
    f['tips'] = []
    for part in re.split(r'\n(?=🟢|🍴|⚠️)', tips.strip()):
        mark = next(k for k in HEAD if part.startswith(k))
        f['tips'].append((mark, part.split(': ', 1)[1].strip()))
    assert [t[0] for t in f['tips']] == list(HEAD), f['id']
    f['faq'] = [(q.strip(), a.strip()) for q, a in re.findall(r'(?m)^س\d: (.*)\nالجواب: (.*)$', block)]
    assert len(f['faq']) == 3, f['id']
    return f


def gi_note(f):
    """The copy's own explanation of its GI value, as a reference note (estimates only)."""
    m = re.match(r'\d+ \((?:منخفض|متوسط|مرتفع) - (.*)\)\.?$', f['gi_line'])
    if not m or f['id'] in PUBLISHED:
        return None
    why = re.sub(r'^تقدير\)?\s*\(?', '', m.group(1).strip()).strip('؛:، ').rstrip('.').rstrip(')')
    sep = ' ' if why.startswith(('ل', 'مبني')) and not why.startswith('لا ') else '، '
    return f'المؤشر الجلايسيمي ({f["gi"]}) تقدير{sep}{why}.'


def main():
    foods = []
    for part in ('ar_corrected_part1.md', 'ar_corrected_part2.md'):
        src = (HERE / part).read_text(encoding='utf-8')
        foods += [parse(b) for b in re.split(r'(?m)^(?=الصنف \d+ \(#\d+\))', src)[1:]]
    foods.sort(key=lambda f: f['id'])
    assert [f['id'] for f in foods] == sorted(SLUG), [f['id'] for f in foods]

    data = (ROOT / 'js' / 'data.js').read_text(encoding='utf-8')
    out = ['# Batch 30 (8 November 2026): approved Arabic copy for 876-905 + 909 (25 foods), generated by build_ar.py\n'
           '# from ar_corrected_part1.md + ar_corrected_part2.md (the before/after tables approved by Dr. Wassim Habib).\n']
    for f in foods:
        line = re.search(r'\{ id: %d,.*\}' % f['id'], data).group(0)
        nut = dict(re.findall(r'(calories|protein|carbs|fat|fiber): ([\d.]+)', line.split('nutrition:')[1]))
        d = {k: float(nut[v]) for k, v in (('kcal', 'calories'), ('protein', 'protein'), ('carbs', 'carbs'),
                                            ('fat', 'fat'), ('fiber', 'fiber'))}
        diff = {k: (f[k], d[k]) for k in d if f[k] is not None and abs(f[k] - d[k]) > 0.05}
        avail = d['carbs'] - d['fiber']
        gl = round(f['gi'] * avail * f['portion'] / 10000, 1) if f['gi'] else None
        copy_gl = re.match(r'([\d.]+)', f['gl_line'])
        f['gl_page'] = gl
        print(f['id'], 'portion', f['portion'], '| GI', f['gi'], '| GL page', gl, '| GL copy',
              copy_gl.group(1) if copy_gl else f['gl_line'][:20], '| data.js diff', diff or '-')
        refs = []
        if f['id'] in PUBLISHED:
            refs.append('المؤشر الجلايسيمي لخبز الجاودار الفنلندي الكامل المخمر (58) قيمة منشورة: ' + PUBLISHED[f['id']])
        elif f['id'] in UNAVAILABLE:
            refs.append('لا يوجد قياس منشور معتمد للمؤشر الجلايسيمي لهذا الصنف، فلا نضع رقماً تقديرياً. وتحذير عرق السوس '
                        'وضغط الدم هو صيغة التحذير الإلزامية في الاتحاد الأوروبي على الحلويات التي تحتوي على حمض '
                        'الغليسيريزين: Regulation (EU) No 1169/2011, Annex III.')
        elif gi_note(f):
            refs.append(gi_note(f))
        body = [f['pulse']]
        for mark, text in f['tips']:
            body += ['', '### ' + HEAD[mark], text]
        faq = '\n\n'.join(f'**{q}**\n{a}' for q, a in f['faq'])
        out.append(f'\n## {f["id"]}\nslug: {SLUG[f["id"]]}\nsugar: غير متوفر\nii: غير مختبر\n'
                   f'title: {f["title"]}\ndesc: {f["desc"]}\n'
                   + (f'brand: {f["brand"]}\n' if f['brand'] else '')
                   + ''.join(f'refs: {r}\n' for r in refs)
                   + '\n' + '\n'.join(body) + '\n\n### FAQ\n' + faq + '\n')
        f['refs'] = refs
    (HERE / 'ar.md').write_text(''.join(out), encoding='utf-8', newline='\n')
    (HERE / 'foods.json').write_text(json.dumps(foods, ensure_ascii=False, indent=1), encoding='utf-8', newline='\n')
    print('ar.md:', len(foods), 'foods')


if __name__ == '__main__':
    main()
